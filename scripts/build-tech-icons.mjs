/**
 * Generates the tech-stack marks from Simple Icons (CC0-1.0).
 *
 *   node scripts/build-tech-icons.mjs
 *
 * Outputs, both generated — never hand-edit either:
 *   public/tech/<id>.svg   the marks themselves, in brand colour
 *   src/lib/tech.ts        metadata only: title, group, brand hex, source
 *
Inlining all 31 paths into the TS module cost 35KB raw / 16KB gzipped on the
 * main bundle, on every page, for icons that appear on one. The app masks the
 * files instead, the same way LogoFull renders from /public.
 *
 * To add or drop a brand, edit STACK below and re-run. Slugs are Simple Icons
 * slugs: `nodedotjs`, not `nodejs`. The script fails loudly on an unknown slug
 * rather than silently emitting a gap.
 *
 * The icon set is CC0, but the trademarks are not: each mark stays the property
 * of its owner, usable to say "we work with this" and nothing more. Check the
 * brand's own guidelines before putting one on a page.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import * as si from 'simple-icons'

/**
 * Grouped the way the site talks about the work — the two tracks in
 * lib/services.ts, not by language or vendor.
 *
 * THIS IS A STARTING SET, NOT A VERIFIED ONE. It is a public claim about what
 * the studio builds with; cut anything Akvega does not actually use.
 */
const STACK = [
  ['Interface', ['react', 'nextdotjs', 'typescript', 'tailwindcss', 'astro', 'vite']],
  ['Mobile', ['flutter', 'expo', 'swift', 'kotlin']],
  ['Backend & data', ['nodedotjs', 'postgresql', 'supabase', 'firebase', 'prisma', 'redis']],
  ['Infrastructure', ['docker', 'vercel', 'cloudflare', 'githubactions']],
  ['Content & commerce', ['sanity', 'wordpress', 'shopify', 'webflow']],
  ['Product surface', ['resend', 'stripe', 'figma']],
  ['Growth', ['googleanalytics', 'googletagmanager', 'googleads', 'meta']],
]

/**
 * Marks that are NOT in Simple Icons because the owner asked to be removed.
 * Drop the vendor's own SVG at public/tech/<id>.svg and fill in `hex`, then it
 * renders like any other. Do not draw a substitute: an approximated logo is
 * worse than a missing one.
 */
const VENDOR_SUPPLIED = [
  {
    id: 'aws',
    title: 'AWS',
    group: 'Infrastructure',
    hex: '#FF9900',
    source: 'https://aws.amazon.com/architecture/icons/',
    note: 'Removed from Simple Icons at Amazon’s request. Use the official Architecture Icons pack and follow the AWS trademark guidelines.',
  },
]

const bySlug = new Map(
  Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]),
)

mkdirSync('public/tech', { recursive: true })

const entries = []
const missing = []

for (const [group, slugs] of STACK) {
  for (const slug of slugs) {
    const icon = bySlug.get(slug)
    if (!icon) { missing.push(slug); continue }

    const svg =
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="${icon.title}">` +
      `<title>${icon.title}</title>` +
      `<path fill="#${icon.hex}" d="${icon.path}"/>` +
      `</svg>\n`
    writeFileSync(`public/tech/${slug}.svg`, svg)

    entries.push({
      id: slug,
      title: icon.title,
      group,
      hex: `#${icon.hex}`,
      source: icon.source,
    })
  }
}

if (missing.length) {
  console.error(`Unknown Simple Icons slugs: ${missing.join(', ')}`)
  process.exit(1)
}

const q = (s) => JSON.stringify(String(s))

const file = `/**
 * GENERATED by scripts/build-tech-icons.mjs — do not edit by hand.
 * Re-run the script to change the set.
 *
 * Marks from Simple Icons (CC0-1.0). The icons are public domain; the
 * trademarks are not. Each mark remains the property of its owner and is used
 * here only to name a technology.
 *
 * Metadata only. The marks live at public/tech/<id>.svg and are rendered by
 * masking that file, so no path data reaches the bundle.
 */
export type TechMark = {
  id: string
  title: string
  group: string
  /** Official brand colour. */
  hex: string
  /** Whether public/tech/<id>.svg exists yet. */
  asset: boolean
  source: string
  /** Set when the mark is not in Simple Icons and must be supplied by hand. */
  note?: string
}

export const techMarks: TechMark[] = [
${entries.map((e) => `  {
    id: ${q(e.id)},
    title: ${q(e.title)},
    group: ${q(e.group)},
    hex: ${q(e.hex)},
    asset: true,
    source: ${q(e.source)},
  },`).join('\n')}
${VENDOR_SUPPLIED.map((e) => `  {
    id: ${q(e.id)},
    title: ${q(e.title)},
    group: ${q(e.group)},
    hex: ${q(e.hex)},
    asset: false,
    source: ${q(e.source)},
    note: ${q(e.note)},
  },`).join('\n')}
]

/** Only the marks whose file exists — what a UI can actually render. */
export const renderableMarks: TechMark[] = techMarks.filter((m) => m.asset)

/** The groups, in the order the script declares them. */
export const techGroups: string[] = [
${[...new Set([...STACK.map(([g]) => g), ...VENDOR_SUPPLIED.map((v) => v.group)])].map((g) => `  ${q(g)},`).join('\n')}
]
`

writeFileSync('src/lib/tech.ts', file)

console.log(`${entries.length} marks written to public/tech/ and src/lib/tech.ts`)
console.log(`${VENDOR_SUPPLIED.length} awaiting a vendor asset: ${VENDOR_SUPPLIED.map((v) => v.id).join(', ')}`)
